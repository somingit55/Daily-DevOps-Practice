num1 = int(input("Enter first number: "))    #taking input from user
num2 = int(input("Enter second number: "))   #str->int conversion is called type casting 

print(type(num1))  #check variable type
print(type(num2))  #check variable type

sum = num1 + num2  #adding two numbers
print("The sum is:", sum)      #result

difference = num1 - num2  #subtracting two numbers
print("The difference is:", difference)      #result